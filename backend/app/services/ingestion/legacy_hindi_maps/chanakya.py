def chanakya_to_unicode(text: str) -> str:
    """Convert Softkey Chanakya-encoded text to Unicode Devanagari."""
    if not text:
        return text
    s = text
    for src, dst in _CHANAKYA_PAIRS:
        if src:
            s = s.replace(src, dst)
    s = s.replace("Z", "üं")
    # ç (short i) typed before the following character — move after it as ि
    while True:
        i = s.find("ç")
        if i < 0:
            break
        if i + 1 >= len(s):
            s = s[:i] + "ि"
            break
        right = s[i + 1]
        s = s[:i] + right + "ि" + s[i + 2 :]
    # ü is reph typed after the syllable — move र् before the preceding consonant
    _matras = set("ांिीुूृेैोौॉँः़्")
    while "ü" in s:
        i = s.index("ü")
        j = i - 1
        while j >= 0 and s[j] in _matras:
            j -= 1
        if j < 0:
            s = "र्" + s[:i] + s[i + 1 :]
        else:
            s = s[:j] + "र्" + s[j:i] + s[i + 1 :]
    return s
